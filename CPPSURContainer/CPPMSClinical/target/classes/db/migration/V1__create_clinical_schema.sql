CREATE TABLE therapeutic_process (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL,
    patient_name VARCHAR(201) NOT NULL,
    patient_dni VARCHAR(8) NOT NULL,
    patient_history_number VARCHAR(20) NOT NULL,
    psychologist_id INTEGER NOT NULL,
    psychologist_name VARCHAR(201) NOT NULL,
    current_phase INTEGER NOT NULL DEFAULT 1,
    start_date DATE NOT NULL,
    end_date DATE,
    observations TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_process_phase CHECK (current_phase BETWEEN 1 AND 4),
    CONSTRAINT chk_process_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE UNIQUE INDEX uq_active_process_patient ON therapeutic_process (patient_id) WHERE active;
CREATE INDEX idx_process_psychologist ON therapeutic_process (psychologist_id, active);

CREATE TABLE initial_interview (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    therapeutic_process_id INTEGER NOT NULL,
    reason_for_consultation TEXT NOT NULL,
    personal_history TEXT,
    family_history TEXT,
    initial_observations TEXT,
    registered_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_interview_process FOREIGN KEY (therapeutic_process_id) REFERENCES therapeutic_process (id),
    CONSTRAINT uq_interview_process UNIQUE (therapeutic_process_id),
    CONSTRAINT chk_interview_reason CHECK (length(trim(reason_for_consultation)) > 0)
);

CREATE TABLE clinical_session (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    therapeutic_process_id INTEGER NOT NULL,
    appointment_id INTEGER NOT NULL,
    session_phase INTEGER NOT NULL,
    evolution TEXT NOT NULL,
    patient_indications TEXT,
    registered_by VARCHAR(201) NOT NULL,
    registered_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_session_process FOREIGN KEY (therapeutic_process_id) REFERENCES therapeutic_process (id),
    CONSTRAINT uq_session_appointment UNIQUE (appointment_id),
    CONSTRAINT chk_session_phase CHECK (session_phase BETWEEN 1 AND 4),
    CONSTRAINT chk_session_evolution CHECK (length(trim(evolution)) > 0)
);
CREATE INDEX idx_session_process_date ON clinical_session (therapeutic_process_id, registered_at DESC);

CREATE FUNCTION reject_clinical_session_update() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'Las sesiones clinicas son inmutables'; END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_clinical_session_immutable BEFORE UPDATE ON clinical_session
FOR EACH ROW EXECUTE FUNCTION reject_clinical_session_update();
