CREATE TABLE cie10_diagnosis (
    code VARCHAR(10) PRIMARY KEY,
    description VARCHAR(300) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_cie10_description ON cie10_diagnosis (lower(description));

CREATE TABLE clinical_hypothesis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    therapeutic_process_id INTEGER NOT NULL,
    clinical_session_id INTEGER,
    phase INTEGER NOT NULL DEFAULT 2,
    hypothesis TEXT NOT NULL,
    therapeutic_plan TEXT NOT NULL,
    registered_by VARCHAR(201) NOT NULL,
    registered_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_hypothesis_process FOREIGN KEY (therapeutic_process_id) REFERENCES therapeutic_process (id),
    CONSTRAINT fk_hypothesis_session FOREIGN KEY (clinical_session_id) REFERENCES clinical_session (id),
    CONSTRAINT chk_hypothesis_phase CHECK (phase = 2),
    CONSTRAINT chk_hypothesis_text CHECK (length(trim(hypothesis)) > 0),
    CONSTRAINT chk_therapeutic_plan_text CHECK (length(trim(therapeutic_plan)) > 0)
);

CREATE INDEX idx_hypothesis_process_date ON clinical_hypothesis (therapeutic_process_id, registered_at DESC);

CREATE TABLE hypothesis_diagnosis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinical_hypothesis_id INTEGER NOT NULL,
    diagnosis_code VARCHAR(10) NOT NULL,
    CONSTRAINT fk_assignment_hypothesis FOREIGN KEY (clinical_hypothesis_id) REFERENCES clinical_hypothesis (id),
    CONSTRAINT fk_assignment_diagnosis FOREIGN KEY (diagnosis_code) REFERENCES cie10_diagnosis (code),
    CONSTRAINT uq_hypothesis_diagnosis UNIQUE (clinical_hypothesis_id, diagnosis_code)
);

